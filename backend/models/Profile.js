const mongoose = require('mongoose');

const profileSchema = new mongoose.Schema({
  headerTitle: { type: String, trim: true, maxlength: 80, default: "" },
  companyName: { type: String, trim: true, maxlength: 160, default: "" },
  legalName: { type: String, trim: true, maxlength: 180, default: "" },
  organizationType: { type: String, trim: true, maxlength: 60, default: "" },
  industry: { type: String, trim: true, maxlength: 120, default: "" },
  contactPerson: { type: String, trim: true, maxlength: 120, default: "" },
  emailAddress: { type: String, trim: true, lowercase: true, maxlength: 160, default: "" },
  website: { type: String, trim: true, maxlength: 200, default: "" },
  companyAddress: { type: String, trim: true, maxlength: 300, default: "" },
  addressLine2: { type: String, trim: true, maxlength: 200, default: "" },
  city: { type: String, trim: true, maxlength: 100, default: "" },
  district: { type: String, trim: true, maxlength: 100, default: "" },
  state: { type: String, trim: true, maxlength: 100, default: "" },
  country: { type: String, trim: true, maxlength: 100, default: "India" },
  cin: { type: String, trim: true, uppercase: true, maxlength: 30, default: "" },
  tan: { type: String, trim: true, uppercase: true, maxlength: 20, default: "" },
  udyamNumber: { type: String, trim: true, uppercase: true, maxlength: 40, default: "" },
  phoneNumber1: { type: String },
  phoneNumber2: { type: String },
  gstin: { type: String },
  pan: { type: String },
  bankName: { type: String },
  accountNo: { type: String },
  branchName: { type: String },
  ifsc: { type: String },
  pinCode: { type: Number },
  stateCode: { type: Number },
  billNoPrefix: { type: String },
  billNoSequence: { type: Number },
  billNoSuffix: { type: String },
  createdBy: { type: String, required: true },
  eWayUserName: { type: String },
  eWayPassword: { type: String },
  customFields: { type: Map, of: mongoose.Schema.Types.Mixed, default: {} },
});

module.exports = mongoose.model('Profile', profileSchema);